"""RESULTS_CFB.md renderer (reads stage results + the summary; every number comes from the run)."""
from __future__ import annotations

from . import narrative as nv
from .narrative_text import _table, defense_summary

_f, _ci = nv._f, nv._ci

MODEL_TEXT = {
    "A_season_avg": "A - season average (last season blended), shrunk; no opponent",
    "B_ewma_rawopp": "B - recent form (EWMA) + opponent's RAW allowed average",
    "C_opp_x_eff": "C - volume x per-play rate (raw)",
    "D_C_ridge_opp_x_eff": "D_C - schedule-adjusted volume x schedule-adjusted rate",
    "D_ridge_sos": "D - schedule-adjusted ratings (ridge, FCS pooled, last season carried)",
    "E_lgbm": "E - LightGBM on the ratings + context",
    "F_stack": "F - stack of B..E (weights fit 2017-19)",
    "G_game_ridge": "G - game-level ridge on the ratings + talent/returning production (margin & total -> team points)",
    "incumbent_retired_engine": "incumbent: retired production engine (expected points)",
    "incumbent_script_engine_baseline": "incumbent: script-engine scoring baseline (what SIFT shows today)",
    "market_close": "closing line (benchmark, not an input)",
    "v2_margin": "2026 'v2' research ensemble (archived walk-forward preds)",
    "v2_total": "2026 'v2' research totals ridge (archived walk-forward preds)",
    "B_ewma": "B - player EWMA shrunk",
    "C_team_x_share": "C - team volume (raw) x player share",
    "D_ridge_team_x_share": "D - team volume (schedule-adjusted) x share",
    "C_team_x_share_x_eff": "C - team volume x share x player efficiency",
    "D_ridge_x_share_x_eff_x_opp": "D - adjusted team volume x share x efficiency x opponent factor",
}


def _fam_table(rows, splits=("validation", "holdout", "holdout_2025", "live_2026"), market=True, scale=None):
    out = []
    for r in rows:
        if r["split"] not in splits:
            continue
        out.append({"Model": MODEL_TEXT.get(r["model"], r["model"]), "Split": r["split"], "n": r["n_obs"], "MAE": r["mae"],
                    "RMSE": r["rmse"], "Bias": r["bias"], "CRPS": r["crps"], "80% cover": r["cover_80"],
                    "PIT var": r["pit_var_ratio"], "vs A (CRPS)": r.get("vs_baseline"), "vs incumbent": r.get("vs_incumbent"),
                    "vs market": r.get("vs_market") if market else None, "Verdict": r.get("verdict")})
    cols = ["Model", "Split", "n", "MAE", "RMSE", "Bias", "CRPS", "80% cover", "PIT var", "vs A (CRPS)", "vs incumbent", "vs market", "Verdict"]
    if not market:
        cols.remove("vs market")
    return _table(out, cols)


def render(S, summary) -> str:
    tf = S.get("team_families", {})
    tp = tf.get("team_points", {})
    rows = tp.get("rows", [])
    best = tp.get("best")

    def g(model, split):
        return next((r for r in rows if r["model"] == model and r["split"] == split), {})
    hb, hA, hI, hS, hM = (g(best, "holdout"), g("A_season_avg", "holdout"), g("incumbent_retired_engine", "holdout"),
                          g("incumbent_script_engine_baseline", "holdout"), g("market_close", "holdout"))
    GF = S.get("game_families", {})
    gr = GF.get("rows", [])

    def gg(fam, model, split):
        return next((r for r in gr if r["family"] == fam and r["model"] == model and r["split"] == split), {})
    mt, mm, mv = gg("margin", best, "holdout"), gg("margin", "market_close", "holdout"), gg("margin", "v2_margin", "holdout")
    tt, tm_, tv = gg("game_total", best, "holdout"), gg("game_total", "market_close", "holdout"), gg("game_total", "v2_total", "holdout")
    mi, ti = gg("margin", "incumbent_retired_engine", "holdout"), gg("game_total", "incumbent_retired_engine", "holdout")
    dd = defense_summary(S)
    L = []
    L.append("# College Football Projection Foundation - results\n")
    L.append("*Research only. Nothing here changes betting authority; the live catalog, execution and sizing paths do not import "
             "this code. Generated by `python -m cfb.run_walkforward` (research/projection_foundation).*\n")
    L.append("## The short version (for a bettor)\n")
    desc = {"G_game_ridge": "a game-level ridge on schedule-adjusted team ratings, talent and returning production, mapped back to "
                            "each team's points", "F_stack": "a stack dominated by schedule-adjusted team ratings"}.get(best, best)
    L.append(f"* **Team points.** The best model (`{best}`, {desc}) misses a team's "
             f"score by **{_f(hb.get('mae'))} points** on average in the 2023-24 holdout (see CFB-TP-02 for how the holdout was used). The season-average baseline misses by "
             f"{_f(hA.get('mae'))}, the retired production engine by {_f(hI.get('mae'))}, the script engine's scoring baseline (what SIFT "
             f"shows) by {_f(hS.get('mae'))} and the **closing line by {_f(hM.get('mae'))}**. The model is clearly better than everything "
             f"the repo had, and still clearly worse than the market (CRPS diff vs market {_ci(hb.get('vs_market'))}).")
    L.append(f"* **Margin / spread.** Holdout margin MAE {_f(mt.get('mae'))} (closing spread {_f(mm.get('mae'))}, retired engine "
             f"{_f(mi.get('mae'))}, archived v2 research ensemble {_f(mv.get('mae'))} on its games). **Total**: {_f(tt.get('mae'))} "
             f"(closing total {_f(tm_.get('mae'))}, retired engine {_f(ti.get('mae'))}, v2 research {_f(tv.get('mae'))}).")
    L.append("* **Distributions are honest.** Team points, totals and margins all come from ONE joint distribution, so ladders never "
             "contradict each other. 80% ranges cover ~80% of outcomes on every split, including 2026 to date.")
    L.append("* **The defensive rankings were unrealistic for a structural reason** (details below): they are season-to-date-only "
             "ratings ranked before the schedule connects teams. " + dd.get("headline", ""))
    L.append("* **No edge claim.** Against the closing spread/total the model's cover/over probabilities are not better than the line; "
             "this is a projection foundation, not a betting signal.\n")

    L.append("## 1. Data inventory\n")
    L.append(_table(summary["inventory"], ["dataset", "seasons", "rows", "pit_class", "notes"]))
    L.append("\nPIT classes: *archived* = captured before kickoff; *reconstructable* = post-game facts only ever used lagged, or "
             "pre-season facts; *retrospective* = computed after the fact (only safe as prior-season inputs); *missing*.\n")
    L.append("## 2. Splits and rules\n")
    for k, v in summary["splits"].items():
        L.append(f"* **{k}**: {v}")
    L.append("\nEvery rating is refit before every week from games that finished earlier (`pf_core.pit.rolling_ridge_ratings`, "
             "relabelled so prior seasons form one block - see `cfb/ratings.py`). Hyper-parameters were tuned on development only, "
             "the winner was picked on validation, and holdout/2025/2026 were scored once for the frozen winner, the baseline, the "
             "incumbents and the market. Comparisons are paired and game-clustered (`pf_core.metrics.cluster_bootstrap_diff`; "
             "negative = first model better). The ARCHETYPE sealed holdout (2014-2020) was already scored and published by its own "
             "protocol; this work trains on those seasons but never touches the archetype frozen parameters, rows or verdicts.\n")
    L.append("## 3. Team families\n")
    for fam, F in tf.items():
        L.append(f"### {fam}\n")
        meta = nv.FAMILY_META.get(fam, {})
        L.append(f"Population: {meta.get('population', '')}. Distribution: `{F['dist_kind']}` (development CRPS by shape: "
                 + ", ".join(f"{k} {v:.4f}" for k, v in F["dist_kind_dev_crps"].items()) + "). Stack weights: "
                 + ", ".join(f"{k} {v:.2f}" for k, v in F["stack_weights"].items() if v > 0.005) + ".\n")
        L.append(_fam_table(F["rows"], market=(fam == "team_points")))
        L.append("")
    L.append("### game_total and margin (derived from the joint team-score model)\n")
    L.append(f"Joint construction chosen on development: `{GF.get('kind')}` (residual correlation between the two teams' "
             f"scores after the model: {_f(GF.get('kinds', {}).get('empirical', {}).get('rho'), 3)}). Line columns: Brier/ECE of "
             "P(home covers the closing spread) and P(over the closing total), pushes excluded.\n")
    out = []
    for r in gr:
        if r["split"] in ("validation", "holdout", "holdout_2025", "live_2026"):
            out.append({"Family": r["family"], "Model": MODEL_TEXT.get(r["model"], r["model"]), "Split": r["split"], "n": r["n_obs"],
                        "MAE": r["mae"], "Bias": r["bias"], "CRPS": r["crps"], "80% cover": r["cover_80"], "PIT var": r["pit_var_ratio"],
                        "vs A": r.get("vs_baseline"), "vs incumbent": r.get("vs_incumbent"), "vs market": r.get("vs_market"),
                        "vs v2 research": r.get("vs_v2_research"), "line Brier": r.get("line_brier"), "line ECE": r.get("line_ece"),
                        "Verdict": "best" if r["model"] == best else ""})
    L.append(_table(out, ["Family", "Model", "Split", "n", "MAE", "Bias", "CRPS", "80% cover", "PIT var", "vs A", "vs incumbent",
                          "vs market", "vs v2 research", "line Brier", "line ECE", "Verdict"]))
    L.append("")
    L.append("## 4. Player families\n")
    if S.get("players"):
        for fam, F in S["players"].items():
            from .players import GATE_FAMILY, FAMILIES
            L.append(f"### {GATE_FAMILY[fam]} ({fam})\n")
            L.append(f"Population: {nv.PLAYER_POP[FAMILIES[fam][0]]}. Distribution `{F['dist_kind']}`. "
                     + (f"Leading passer did not record an attempt in {F['non_appearance_rate']:.1%} of candidate games. "
                        if "non_appearance_rate" in F else "") + "\n")
            L.append(_fam_table(F["rows"], market=False))
            L.append("")
    for fam, why in nv.INSUFFICIENT.items():
        L.append(f"* **{fam}: INSUFFICIENT DATA.** {why}")
    L.append("")
    L.append("## 5. Experiments\n")
    for e in summary["experiments"]:
        L.append(f"### {e['id']}\n")
        for k in ("question", "hypothesis", "method", "data", "result", "interpretation", "decision"):
            L.append(f"* **{k.capitalize()}:** {e[k]}")
        L.append("")
    L.append("## 6. Error investigations\n")
    L.append(_table(summary["error_investigations"], ["pattern", "frequency", "impact", "cause", "status", "action"]))
    L.append("\n## 7. The defensive rankings: diagnosis\n")
    L.append("**Where they come from.** `src/cfb_edge_finder/scripting/adjust.py` (`fit_metric`, `rank_in_universe`) via "
             "`matchup.unit_metric`, published per metric in every script-engine artifact (`rank`, `universe_size`) and in the "
             "app explorer. " + dd.get("cause", ""))
    L.append("\n**Rank reliability** (Spearman rank correlation between a method's week-w defensive points rating and a rating fitted "
             "only on weeks >= w of the same season; mean over 2016-2025; top-10 overlap out of 10):\n")
    L.append(_table(dd.get("table", []), ["week", "adjusted", "dcarry", "raw", "top10_adjusted", "top10_dcarry", "top10_raw",
                                          "share_unstable_fits"],
                    ["week", "script engine (season-to-date ridge)", "ridge + prior seasons (this work)", "raw points allowed",
                     "top-10 overlap SE", "top-10 overlap carry", "top-10 overlap raw", "share of fits flagged unstable"]))
    L.append("\n**FCS credit** (next FBS game's points allowed, weeks 2-4, by whether the defence already played an FCS team; "
             "bias = projection - actual):\n")
    L.append(_table(dd.get("fcs_credit", []), ["model", "defence_played_fcs_earlier", "n", "bias_pts_allowed", "mae"]))
    L.append(f"\n**Pace confound**: the gap between a defence's points-per-game rank and points-per-drive rank correlates "
             f"{_f(dd.get('pace_corr_rankgap_ownplays'))} (Spearman, mean over seasons, week 8) with its own offence's plays per game.\n")
    L.append(_table(dd.get("pace", []), ["season", "n", "corr_rankgap_ownplays", "corr_rankgap_ownposs", "mean_abs_rank_gap"]))
    L.append("\n**2026, replayed through the production code** (top-10 defences by the script engine vs the carried ridge):\n")
    for s in dd.get("snapshots_2026", [])[:3] + dd.get("snapshots_2026", [])[-1:]:
        L.append(f"* week {s['week']} (fit stable: {s['stable']}, FBS schedule components: {s['components']}): SE "
                 + "; ".join(s["script_engine_top10"]) + " | carry: " + ", ".join(s["ridge_carry_top10"]))
    L.append("\n" + dd.get("interpretation", "") + " " + dd.get("action", "") + "\n")
    L.append("## 8. Opponent adjustment (strength of schedule)\n")
    L.append(summary["opponent_adjustment"]["summary"] + "\n")
    L.append(_table([r for r in summary["opponent_adjustment"]["results"] if "comparison" in r],
                    ["split", "population", "comparison", "n_obs", "mae_a", "mae_b", "mean_diff", "ci95"]))
    L.append("\nBy week (D = schedule-adjusted ridge; Dcs = same ridge, current season only; mkt = closing line):\n")
    L.append(_table([r for r in summary["opponent_adjustment"]["results"] if "weeks" in r],
                    ["split", "weeks", "a", "b", "n_obs", "mae_a", "mae_b", "mean_diff", "ci95"]))
    L.append("\n## 9. Opportunity (plays) research\n")
    L.append(summary["opportunity"]["summary"] + "\n")
    L.append(_table(summary["opportunity"]["results"], ["family", "model", "mae", "crps", "bias"]))
    L.append("\n## 10. Calibration\n")
    L.append(summary["calibration"]["summary"] + "\n")
    L.append(_table(summary["calibration"]["results"], ["family", "split", "cover_50", "cover_80", "cover_90", "pit_var_ratio",
                                                       "line_brier", "line_ece", "hit_rate_when_p_gt_0.6", "n_p_gt_0.6"]))
    for t in summary["calibration"].get("threshold_tables", []):
        if t["split"] in ("holdout",):
            L.append(f"\nReliability vs the closing line, {t['family']}, {t['split']}:\n")
            L.append(_table(t["calibration"], ["bin", "n", "mean_p", "hit_rate"]))
    se = summary["calibration"].get("script_engine_v2", {})
    if se.get("n_games"):
        L.append(f"\n**Script engine v2 CONTROL ranges on 2026** ({se['n_games']} games): central-50 coverage "
                 f"{_f(se['coverage_50'], 3)}, central-80 {_f(se['coverage_80'], 3)}; stated win rate {_f(se['mean_stated_win_rate'], 3)} vs "
                 f"realised {_f(se['realised_win_rate'], 3)}. These are tier-level historical frequencies, not game probabilities, and "
                 "must not be presented as calibrated forecasts.\n")
        L.append(_table(se.get("by_tier", []), ["tier", "n", "stated", "realised", "cov50", "cov80"]))
    L.append("\n## 11. Projection Quality Gate\n")
    G = summary.get("gate", {})
    if G:
        L.append(f"Run on every validation/holdout team-points projection (n={G['summary'].get('n')}): status counts "
                 f"{G['summary'].get('status_counts')}; checks {G['summary'].get('check_counts')}.\n")
        for sp, d in G.get("error_by_status", {}).items():
            if sp == "by_check":
                continue
            L.append(f"* {sp}: " + "; ".join(f"{k}: n {v['n']}, MAE {v['mae']:.2f}, rate {v['rate']:.1%}" for k, v in d.items() if isinstance(v, dict))
                     + (f"; REVIEW minus PASS MAE {d.get('review_minus_pass_mae'):+.2f}" if d.get("review_minus_pass_mae") is not None else ""))
        for sp, d in G.get("error_by_status", {}).get("by_check", {}).items():
            L.append(f"* {sp}, by check: " + "; ".join(f"{k}: flagged n {v['n_flagged']}, MAE {v['mae_flagged']:.2f} vs unflagged {v['mae_unflagged']:.2f}" for k, v in d.items()))
        L.append("\nA REVIEW flag means 'wider uncertainty / prior-driven', not 'wrong': the early-opponent flag marks week 1-4 "
                 "games whose projections are mostly last season's ratings. Flagged projections have only slightly larger "
                 "errors in points (the distribution is already widened by construction); the flags are informative about "
                 "*why* a number is uncertain rather than strong error predictors. No coherence BLOCK occurred (the joint "
                 "model makes totals and margins exact).")
    L.append("\n## 12. Failed experiments\n")
    for f in summary["failed_experiments"]:
        L.append(f"* **{f['name']}** - {f['what_was_learned']} -> {f['changes_future_decisions']}")
    L.append("\n## 13. Readiness\n")
    L.append(_table([{"family": f["family"], "readiness": f["readiness"], "model": f.get("best_model"), "why": f["readiness_reason"]}
                     for f in summary["families"]], ["family", "readiness", "model", "why"]))
    L.append("\n## 14. Priorities\n")
    L.append(_table(summary["priorities"], ["rank", "item", "impact", "evidence", "complexity", "data"]))
    L.append("\n## 15. pf_core findings (library untouched; worked around)\n")
    for p in summary.get("pf_core_findings", []):
        L.append(f"* **{p['where']}** - {p['finding']} Workaround: {p['workaround']}")
    L.append("\n## 16. Reproduce / forward projections\n")
    L.append("```\ncd research/projection_foundation\npython -m cfb.paths            # fetch caches (research-data branch, sportsdataverse releases)\n"
             "python -m cfb.run_walkforward  # full backtest -> results/summary.json, results/experiments/, RESULTS_CFB.md\n"
             "python -m cfb.project          # current week -> results/projections_latest.json (sift.projections.v1)\n"
             "python -m pytest -q tests\n```\n")
    L.append("`.github/workflows/projection-foundation.yml` runs the forward projection weekly in season (Tue/Fri) and on dispatch and "
             "publishes to the isolated `projection-data` orphan branch (projections/cfb/latest.json, timestamped copies, "
             "summary/cfb/latest.json). It is inert until merged to the default branch.\n")
    return "\n".join(L)
